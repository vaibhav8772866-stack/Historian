/**
 * Search Directory by Employee ID, Name, or Email
 */
export function searchEmployeeDirectory(query) {
  if (!query) return [];

  const cleanQuery = String(query).trim().toLowerCase();

  // 1. Exact Employee ID match (e.g. EMP-1042, EMP-1001)
  const idMatch = EMPLOYEE_DIRECTORY.filter(emp => 
    emp.employee_id.toLowerCase() === cleanQuery || 
    emp.employee_id.toLowerCase().replace('-', '') === cleanQuery.replace('-', '')
  );
  if (idMatch.length > 0) return idMatch;

  // 2. Partial ID match
  const partialIdMatches = EMPLOYEE_DIRECTORY.filter(emp =>
    emp.employee_id.toLowerCase().includes(cleanQuery)
  );
  if (partialIdMatches.length > 0) return partialIdMatches;

  // 3. Name or Email or Department match
  return EMPLOYEE_DIRECTORY.filter(emp =>
    emp.name.toLowerCase().includes(cleanQuery) ||
    emp.email.toLowerCase().includes(cleanQuery) ||
    emp.department.toLowerCase().includes(cleanQuery) ||
    emp.designation.toLowerCase().includes(cleanQuery)
  );
}
